"""Render Kubernetes manifests for a stack from the catalog, profile and calibrations.

A stack renders two ways:

- the deployable sim stack (`render_deploy`), committed as deploy/<stack>/k8s/;
- an evaluation stack for one latency variant (`render_eval`): the real GPU
  pods and the sim pods side by side, built from the same engine settings.
"""

import copy
import hashlib
import json
from pathlib import Path

import yaml

from simstack.catalog import (
    REPO_ROOT,
    UNIT_BETA,
    VARIANT_TYPES,
    Stack,
    load_calibrations,
    load_hardware,
    load_model,
    load_profile,
    resolve,
)

GENERATED_HEADER = (
    "# Generated by `python -m simstack render`; do not edit. Change the\n"
    "# catalog, profile, calibrations or stack.yaml and re-render instead.\n"
)


class _Dumper(yaml.SafeDumper):
    pass


def _str_presenter(dumper, data):
    style = "|" if "\n" in data else None
    return dumper.represent_scalar("tag:yaml.org,2002:str", data, style=style)


_Dumper.add_representer(str, _str_presenter)


def to_yaml(doc: dict) -> str:
    return yaml.dump(doc, Dumper=_Dumper, sort_keys=False, width=1000)


def config_hash(configs: list[dict]) -> str:
    """Short content hash: sha256 of the sorted-key JSON of the sim config(s)."""
    payload = configs[0] if len(configs) == 1 else configs
    return hashlib.sha256(json.dumps(payload, sort_keys=True).encode()).hexdigest()[:6]


def build_sim_config(hf_config: dict, hardware: dict, weight_dtype: str,
                     latency: dict) -> dict:
    sim = {k: v for k, v in hf_config.items() if k != "latency"}
    sim["architectures"] = ["SimulatedForCausalLM"]
    lat = copy.deepcopy(latency)
    if lat["type"] == "physics":
        lat = {
            "type": "physics",
            "hardware": {
                "peak_tflops": hardware["peak_tflops"],
                "hbm_gbps": hardware["hbm_gbps"],
                "weight_dtype": weight_dtype,
            },
            "beta": [float(b) for b in lat.get("beta", UNIT_BETA)],
            **{k: v for k, v in lat.items() if k not in ("type", "beta")},
        }
    lat.setdefault("deterministic_length", True)
    sim["latency"] = lat
    return sim


def _env(name, value):
    return {"name": name, "value": str(value)}


_HF_TOKEN = {
    "name": "HF_TOKEN",
    "valueFrom": {"secretKeyRef": {"name": "hf-token", "key": "token",
                                   "optional": True}},
}


def _http_probe(port, **kw):
    return {"httpGet": {"path": "/health", "port": port}, **kw}


def _deployment(name, containers, volumes, *, role=None, init=None,
                node_selector=None):
    labels = {"app": name}
    if role:
        labels["role"] = role
    pod = {}
    if node_selector:
        pod["nodeSelector"] = dict(node_selector)
    if init:
        pod["initContainers"] = init
    pod["containers"] = containers
    pod["volumes"] = volumes
    return {
        "apiVersion": "apps/v1",
        "kind": "Deployment",
        "metadata": {"name": name, "labels": dict(labels)},
        "spec": {
            "replicas": 1,
            "selector": {"matchLabels": {"app": name}},
            "template": {"metadata": {"labels": dict(labels)}, "spec": pod},
        },
    }


def _service(name, app, *, nixl_port=None):
    ports = [{"name": "http", "port": 8000, "targetPort": 8000}]
    if nixl_port:
        ports.append({"name": "nixl-side", "port": nixl_port,
                      "targetPort": nixl_port})
    return {
        "apiVersion": "v1",
        "kind": "Service",
        "metadata": {"name": name},
        "spec": {"selector": {"app": app}, "ports": ports, "type": "ClusterIP"},
    }


_NIXL_PORT = {"prefill": 5600, "decode": 5601}
_KV_ROLE = {"prefill": "kv_producer", "decode": "kv_consumer"}


class Renderer:
    def __init__(self, stack: Stack, root: Path = REPO_ROOT):
        self.stack = stack
        self.hw = load_hardware(stack.hardware, root)
        self.meta, self.hf_config = load_model(stack.model, root)
        self.profile = load_profile(stack.profile, root)
        self.records = load_calibrations(stack.model, stack.hardware, root)
        engine = dict(self.hw.get("vllm_defaults") or {})
        engine.update(self.profile.get("engine") or {})
        # Never ask for more context than the model supports.
        max_pos = self.hf_config.get("max_position_embeddings")
        if max_pos:
            engine["max_model_len"] = min(engine["max_model_len"], max_pos)
        self.engine = engine

    # ---- latency resolution ------------------------------------------------

    @property
    def roles(self) -> list[str]:
        return ["standalone"] if self.stack.topology == "standalone" else [
            "prefill", "decode"]

    @property
    def tuned_role(self) -> str:
        """The pod whose /sim/config the auto-tuner drives."""
        return self.roles[-1]

    def query(self, role: str) -> dict:
        q = {"topology": self.stack.topology, "tp": self.stack.tp}
        if role != "standalone":
            q["role"] = role
        return q

    def resolve(self, variant: str = "physics") -> dict[str, dict]:
        """Map each pod role to the calibration record it uses."""
        if variant not in VARIANT_TYPES:
            raise ValueError(
                f"unknown variant {variant!r}; known: {sorted(VARIANT_TYPES)}")
        if variant == "physics-beta-1.0":
            rec = {"latency": {"type": "physics", "beta": UNIT_BETA},
                   "method": "assumed", "note": "uncalibrated baseline"}
            return {role: rec for role in self.roles}
        return {role: resolve(self.records, VARIANT_TYPES[variant],
                              self.query(role))
                for role in self.roles}

    def sim_configs(self, variant: str = "physics") -> dict[str, dict]:
        return {
            role: build_sim_config(self.hf_config, self.hw,
                                   self.meta.get("weight_dtype", "bfloat16"),
                                   rec["latency"])
            for role, rec in self.resolve(variant).items()
        }

    # ---- names ---------------------------------------------------------------

    def base_name(self, configs: dict[str, dict]) -> str:
        distinct = _distinct(configs)
        topo = self.stack.topology
        if self.stack.tp > 1:
            topo += f"-tp{self.stack.tp}"
        return f"vllm-{self.stack.model}-{topo}-{config_hash(distinct)}"

    # ---- config maps ---------------------------------------------------------

    def _configmaps(self, base, configs, records):
        """One ConfigMap per distinct sim config; returns (docs, role -> name)."""
        shared = len(_distinct(configs)) == 1
        docs, names = [], {}
        for role, cfg in configs.items():
            name = f"{base}-config" if shared else f"{base}-{role}-config"
            names[role] = name
            if any(d["metadata"]["name"] == name for d in docs):
                continue
            rec = records[role]
            annotations = {"vllm-model-sim/calibration-method":
                           rec.get("method", "unknown")}
            if rec.get("match"):
                annotations["vllm-model-sim/calibration-match"] = ",".join(
                    f"{k}={v}" for k, v in rec["match"].items())
            docs.append({
                "apiVersion": "v1",
                "kind": "ConfigMap",
                "metadata": {"name": name, "annotations": annotations},
                "data": {"config.json": json.dumps(cfg, indent=2) + "\n"},
            })
        return docs, names

    def _sim_config_files(self, configs) -> dict[str, str]:
        files = {"sim-config.json":
                 json.dumps(configs[self.tuned_role], indent=2) + "\n"}
        for role, cfg in configs.items():
            if cfg != configs[self.tuned_role]:
                files[f"{role}-sim-config.json"] = json.dumps(cfg, indent=2) + "\n"
        return files

    # ---- containers ----------------------------------------------------------

    def _engine_flags(self) -> list[tuple[str, str]]:
        flags = [("--max-model-len", self.engine["max_model_len"])]
        for key in ("max_num_batched_tokens", "max_num_seqs"):
            if key in self.engine:
                flags.append(("--" + key.replace("_", "-"), self.engine[key]))
        return flags

    def _sim_container(self, role, config_name, *, tuner, hf_cache):
        sim = self.profile["sim"]
        port = 8200 if role == "decode" else 8000
        per = sim["cpus_per_rank"]
        cpus = per * self.stack.tp
        mem = sim["memory_gib_per_rank"] * self.stack.tp
        hf = self.meta["hf_id"]

        cmd = ["vllm", "serve", "/model", "--load-format=dummy",
               f"--tokenizer={hf}",
               f"--served-model-name={self.meta['served_model_name']}",
               f"--gpu-memory-utilization={sim['gpu_memory_utilization']}"]
        if self.stack.tp > 1:
            cmd.append(f"--tensor-parallel-size={self.stack.tp}")
        cmd += [f"{flag}={value}" for flag, value in self._engine_flags()]
        if role == "decode":
            cmd.append(f"--port={port}")
        if role != "standalone":
            kv = self.hw.get("kv_transfer") or {}
            cmd += ["--kv-transfer-config", json.dumps({
                "kv_connector": "SimulatedNixlConnector",
                "kv_role": _KV_ROLE[role],
                "kv_connector_extra_config": kv,
            }, separators=(",", ":"))]

        env = [_env("PYTHONPATH", "/plugins"),
               _env("VLLM_CPU_KVCACHE_SPACE", sim["kv_cache_space_gib"]),
               # One CPU range per TP rank, "|"-separated (vLLM CPU backend).
               _env("VLLM_CPU_OMP_THREADS_BIND", "|".join(
                   f"{r * per}-{(r + 1) * per - 1}"
                   for r in range(self.stack.tp)))]
        if role != "standalone":
            env += [{"name": "VLLM_NIXL_SIDE_CHANNEL_HOST",
                     "valueFrom": {"fieldRef": {"fieldPath": "status.podIP"}}},
                    _env("VLLM_NIXL_SIDE_CHANNEL_PORT", _NIXL_PORT[role])]
        if tuner:
            env += [_env("VLLM_PLUGINS", "simulated_model,sim_tuner"),
                    _env("VLLM_SIM_TUNER", "1"),
                    _env("VLLM_SIM_CONFIG_PATH", "/tmp/sim-config.json")]
        env += [_env("HOME", "/tmp"), _env("XDG_CACHE_HOME", "/tmp/cache")]
        if hf_cache == "pvc":
            env += [_env("HF_HOME", "/hf-cache"), _env("HF_HUB_CACHE", "/hf-cache")]
        elif hf_cache == "emptydir":
            env.append(_env("HF_HOME", "/tmp/hf"))
        env.append(_HF_TOKEN)

        ports = [{"containerPort": port,
                  "name": "vllm" if role == "decode" else "http"}]
        if role != "standalone":
            ports.append({"containerPort": _NIXL_PORT[role], "name": "nixl-side"})

        mounts = [{"name": "plugins", "mountPath": "/plugins"},
                  {"name": "model-config", "mountPath": "/model", "readOnly": True},
                  {"name": "dshm", "mountPath": "/dev/shm"}]
        if hf_cache:
            mounts.append({"name": "hf-cache",
                           "mountPath": "/hf-cache" if hf_cache == "pvc" else "/tmp/hf"})

        container = {
            "name": "vllm",
            "image": sim["image"],
            "command": cmd,
            "env": env,
            "ports": ports,
            "startupProbe": _http_probe(port, periodSeconds=5, failureThreshold=30),
            "livenessProbe": _http_probe(port, periodSeconds=10, failureThreshold=3),
            "readinessProbe": _http_probe(port, periodSeconds=5, failureThreshold=3),
            "resources": {
                "requests": {"cpu": str(cpus), "memory": f"{mem}Gi"},
                "limits": {"cpu": str(cpus), "memory": f"{mem}Gi"},
            },
            "volumeMounts": mounts,
        }

        volumes = [{"name": "plugins", "emptyDir": {}},
                   {"name": "model-config", "configMap": {"name": config_name}},
                   {"name": "dshm", "emptyDir": {
                       "medium": "Memory",
                       "sizeLimit": "256Mi" if role == "standalone" else "1Gi"}}]
        if hf_cache == "pvc":
            volumes.append({"name": "hf-cache", "persistentVolumeClaim": {
                "claimName": self.pvc_name}})
        elif hf_cache == "emptydir":
            volumes.append({"name": "hf-cache", "emptyDir": {"sizeLimit": "8Gi"}})
        return container, volumes

    def _install_plugin(self):
        return [{
            "name": "install-plugin",
            "image": self.profile["sim"]["deps_image"],
            "imagePullPolicy": "Always",
            "command": ["sh", "-c", "cp -r /plugins/* /mnt/plugins/"],
            "volumeMounts": [{"name": "plugins", "mountPath": "/mnt/plugins"}],
        }]

    def _real_container(self, role):
        real = self.profile["real"]
        port = 8200 if role == "decode" else 8000
        tp = self.stack.tp
        hf = self.meta["hf_id"]
        args = ["--served-model-name", self.meta["served_model_name"],
                "--tokenizer", hf,
                "--tensor-parallel-size", str(tp),
                "--gpu-memory-utilization", str(real["gpu_memory_utilization"])]
        for flag, value in self._engine_flags():
            args += [flag, str(value)]
        if role == "decode":
            args += ["--port", str(port)]
        if role != "standalone":
            args += ["--kv-transfer-config", json.dumps(
                {"kv_connector": "NixlConnector", "kv_role": _KV_ROLE[role]},
                separators=(",", ":"))]

        env = []
        if role != "standalone":
            env += [{"name": "VLLM_NIXL_SIDE_CHANNEL_HOST",
                     "valueFrom": {"fieldRef": {"fieldPath": "status.podIP"}}},
                    _env("VLLM_NIXL_SIDE_CHANNEL_PORT", _NIXL_PORT[role])]
        env += [_env("HF_HOME", "/tmp/hf"), _env("HOME", "/tmp"),
                _env("XDG_CACHE_HOME", "/tmp/cache"), _HF_TOKEN]

        ports = [{"containerPort": port,
                  "name": "vllm" if role == "decode" else "http"}]
        if role != "standalone":
            ports.append({"containerPort": _NIXL_PORT[role], "name": "nixl-side"})

        mem = f"{real['memory_gib_per_gpu'] * tp}Gi"
        return {
            "name": "vllm",
            "image": real["image"],
            "command": ["vllm", "serve", hf],
            "args": args,
            "env": env,
            "ports": ports,
            "livenessProbe": _http_probe(port, initialDelaySeconds=600,
                                         periodSeconds=10, failureThreshold=6),
            "readinessProbe": _http_probe(port, initialDelaySeconds=600,
                                          periodSeconds=10, failureThreshold=3),
            "resources": {
                "requests": {"memory": mem, "nvidia.com/gpu": tp},
                "limits": {"memory": mem, "nvidia.com/gpu": tp},
            },
            "volumeMounts": [{"name": "hf-cache", "mountPath": "/tmp/hf"}],
        }

    def _sidecar(self, prefill_service):
        return {
            "name": "sidecar",
            "image": self.profile["sidecar"]["image"],
            "imagePullPolicy": "Always",
            "args": ["--kv-connector=nixlv2", "--port=8000", "--secure-proxy=false"],
            "env": [_env("PREFILLER_HOST", f"{prefill_service}:8000"),
                    _env("DECODER_HOST", "localhost:8200")],
            "ports": [{"containerPort": 8000, "name": "http"}],
            "livenessProbe": _http_probe(8000, initialDelaySeconds=10,
                                         periodSeconds=10, failureThreshold=3),
            "readinessProbe": _http_probe(8000, initialDelaySeconds=5,
                                          periodSeconds=5, failureThreshold=3),
            "resources": {"requests": {"cpu": "500m", "memory": "512Mi"},
                          "limits": {"cpu": "1", "memory": "1Gi"}},
        }

    def _sim_deployment(self, name, role, config_name, *, tuner, hf_cache,
                        prefill_service=None):
        container, volumes = self._sim_container(
            role, config_name, tuner=tuner, hf_cache=hf_cache)
        containers = [container]
        if role == "decode":
            containers.insert(0, self._sidecar(prefill_service))
        return _deployment(name, containers, volumes,
                           role=None if role == "standalone" else role,
                           init=self._install_plugin())

    def _real_deployment(self, name, role, prefill_service=None):
        containers = [self._real_container(role)]
        if role == "decode":
            containers.insert(0, self._sidecar(prefill_service))
        volumes = [{"name": "hf-cache", "emptyDir": {
            "sizeLimit": f"{self.profile['real']['hf_cache_gib']}Gi"}}]
        return _deployment(name, containers, volumes,
                           role=None if role == "standalone" else role,
                           node_selector=self.hw.get("node_selector"))

    @property
    def pvc_name(self) -> str:
        return f"vllm-{self.stack.model}-hf-cache"

    def _pvc(self):
        return {
            "apiVersion": "v1",
            "kind": "PersistentVolumeClaim",
            "metadata": {"name": self.pvc_name},
            "spec": {
                "accessModes": ["ReadWriteMany"],
                "storageClassName": self.profile["sim"]["hf_cache_storage_class"],
                "resources": {"requests": {"storage": "1Gi"}},
            },
        }

    def _benchmark_job(self, base):
        image = self.profile["benchmark"]["image"]
        repo = "vllm-model-sim"
        script = (
            "set -euo pipefail\n"
            "mkdir -p /tmp/src /tmp/pydeps\n"
            'python -c "import urllib.request, tarfile; \\\n'
            f"  urllib.request.urlretrieve('https://github.com/llm-d-extensions/{repo}"
            "/archive/refs/heads/main.tar.gz', '/tmp/src.tgz'); \\\n"
            "  tarfile.open('/tmp/src.tgz').extractall('/tmp/src')\"\n"
            "pip install --no-cache-dir --target=/tmp/pydeps pyyaml\n"
            f'export PYTHONPATH="/tmp/src/{repo}-main:/tmp/pydeps"\n'
            f"cd /tmp/src/{repo}-main\n"
            "python -m evaluation.run_eval eval \\\n"
            f"  --real-url http://{base}-real:8000 \\\n"
            f"  --sim-url http://{base}-sim:8000 \\\n"
            f"  --tokenizer {self.meta['hf_id']} \\\n"
            f"  --sweep deploy/{self.stack.name}/sweep.yaml \\\n"
            "  --out /out\n"
        )
        name = f"{base}-benchmark"
        return {
            "apiVersion": "batch/v1",
            "kind": "Job",
            "metadata": {"name": name, "labels": {"app": name}},
            "spec": {
                "backoffLimit": 0,
                "template": {
                    "metadata": {"labels": {"app": name}},
                    "spec": {
                        "restartPolicy": "Never",
                        "containers": [{
                            "name": "benchmark",
                            "image": image,
                            "command": ["/bin/bash", "-c", script],
                            "env": [_env("HOME", "/tmp"),
                                    _env("XDG_CACHE_HOME", "/tmp/cache"),
                                    _env("HF_HOME", "/tmp/hf"), _HF_TOKEN],
                            "volumeMounts": [{"name": "output", "mountPath": "/out"}],
                        }],
                        "volumes": [{"name": "output", "emptyDir": {}}],
                    },
                },
            },
        }

    # ---- stacks ----------------------------------------------------------------

    def render_deploy(self) -> dict[str, str]:
        """The deployable sim stack (calibrated physics), file name -> content."""
        records = self.resolve("physics")
        configs = self.sim_configs("physics")
        base = self.base_name(configs)
        cms, cm_names = self._configmaps(base, configs, records)
        docs = {"configmap.yaml": cms}
        if self.stack.topology == "standalone":
            docs["pvc.yaml"] = [self._pvc()]
            docs["deployment.yaml"] = [self._sim_deployment(
                base, "standalone", cm_names["standalone"], tuner=False,
                hf_cache="pvc")]
            docs["service.yaml"] = [_service(base, base)]
        else:
            pf, dc = f"{base}-prefill", f"{base}-decode"
            docs["prefill-deployment.yaml"] = [self._sim_deployment(
                pf, "prefill", cm_names["prefill"], tuner=False,
                hf_cache="emptydir")]
            docs["prefill-service.yaml"] = [_service(pf, pf, nixl_port=5600)]
            docs["decode-deployment.yaml"] = [self._sim_deployment(
                dc, "decode", cm_names["decode"], tuner=False,
                hf_cache="emptydir", prefill_service=pf)]
            docs["decode-service.yaml"] = [_service(dc, dc)]
        files = _dump(docs)
        files.update(self._sim_config_files(configs))
        return files

    def render_eval(self, variant: str) -> dict[str, str]:
        """Real + sim stack for one latency variant, laid out for eval.sh."""
        records = self.resolve(variant)
        configs = self.sim_configs(variant)
        base = self.base_name(configs)
        cms, cm_names = self._configmaps(base, configs, records)
        docs = {"configmap.yaml": cms}
        if self.stack.topology == "standalone":
            docs["real-deployment.yaml"] = [self._real_deployment(
                f"{base}-real", "standalone")]
            docs["real-service.yaml"] = [_service(f"{base}-real", f"{base}-real")]
            docs["sim-deployment.yaml"] = [self._sim_deployment(
                f"{base}-sim", "standalone", cm_names["standalone"], tuner=True,
                hf_cache=None)]
            docs["sim-service.yaml"] = [_service(f"{base}-sim", f"{base}-sim")]
        else:
            for side in ("real", "sim"):
                pf, dc = f"{base}-{side}-prefill", f"{base}-{side}-decode"
                if side == "real":
                    docs["real-prefill-deployment.yaml"] = [
                        self._real_deployment(pf, "prefill")]
                    docs["real-decode-deployment.yaml"] = [
                        self._real_deployment(dc, "decode", prefill_service=pf)]
                else:
                    docs["sim-prefill-deployment.yaml"] = [self._sim_deployment(
                        pf, "prefill", cm_names["prefill"], tuner=False,
                        hf_cache=None)]
                    docs["sim-decode-deployment.yaml"] = [self._sim_deployment(
                        dc, "decode", cm_names["decode"], tuner=True,
                        hf_cache=None, prefill_service=pf)]
                docs[f"{side}-prefill-service.yaml"] = [
                    _service(pf, pf, nixl_port=5600)]
                docs[f"{side}-service.yaml"] = [_service(f"{base}-{side}", dc)]
        docs["benchmark-job.yaml"] = [self._benchmark_job(base)]
        files = _dump(docs)
        files.update(self._sim_config_files(configs))
        return files


def _distinct(configs: dict[str, dict]) -> list[dict]:
    out = []
    for cfg in configs.values():
        if cfg not in out:
            out.append(cfg)
    return out


def _dump(docs: dict[str, list[dict]]) -> dict[str, str]:
    return {name: GENERATED_HEADER + "---\n".join(to_yaml(d) for d in ds)
            for name, ds in docs.items()}


def write_files(files: dict[str, str], out_dir: Path) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    for name, text in files.items():
        (out_dir / name).write_text(text)
